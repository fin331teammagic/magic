"""EXPLORATORY: turn one LLM-question screen into a team summary.

Reads a folder written by ``code/explore_llm_questions.py`` and writes, in
that folder:

- ``SUMMARY.md``: scoring details (for the write-up), variation flags,
  model agreement, overlap, the one-question-at-a-time table, the
  Amendment 6 leads, the Q20 benchmark and the all-questions block. Every
  number is copied from the screen's CSVs, so it can be checked against them.
- ``call_check_sample.csv``: for the strongest questions, a few calls per
  score value with every model's score, for reading transcripts locally
  (``code/show_transcript.py``). Event IDs and scores only, no transcript text.

    python code/summarize_llm_screen.py outputs/exploratory_llm_questions/v2.0_gemma4
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(ROOT / "dashboard"))
import explore_llm_questions as ex  # noqa: E402
import exploratory as lead_rule  # noqa: E402  (the dashboard applies the same rule)

MOSTLY_NULL_SHARE = 0.50
TOP_QUESTIONS = 3
CALLS_PER_VALUE = 3


def fmt(value, digits=3):
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return "—"
    if isinstance(value, (bool, np.bool_)):
        return "yes" if value else "no"
    if isinstance(value, (int, np.integer)):
        return str(value)
    if isinstance(value, (float, np.floating)):
        return f"{value:.{digits}f}"
    return str(value)


def table(frame, columns, headers, digits=None):
    digits = digits or {}
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for _, row in frame.iterrows():
        lines.append("| " + " | ".join(fmt(row[c], digits.get(c, 3)) for c in columns) + " |")
    return "\n".join(lines)


def read(folder, name):
    path = folder / f"{name}.csv"
    return pd.read_csv(path) if path.exists() and path.stat().st_size else None


def top_questions(leads, n=TOP_QUESTIONS):
    """Lead questions first, then the lowest BH q (consensus row if present)."""
    ranked = leads.sort_values(["proposed_lead", "bh_q_within_model"], ascending=[False, True])
    return list(dict.fromkeys(ranked["variable"]))[:n]


def call_sample(score_files, questions, sample_ids, per_value=CALLS_PER_VALUE, seed=ex.rm.SEED):
    """A few calls per score value of each question, with every model's score."""
    specs = {}
    for _, row in score_files.iterrows():
        specs.setdefault(row["model"], []).append(Path(row["file"]))
    scores = None
    for model, paths in specs.items():
        frame, _, _ = ex.load_model(paths)
        keep = [q for q in questions if q in frame]
        frame = frame[["event_id", *keep]].rename(columns={q: f"{q}__{model}" for q in keep})
        scores = frame if scores is None else scores.merge(frame, on="event_id", how="outer")
    scores = scores[scores["event_id"].isin(sample_ids)]
    rows = []
    for question in questions:
        columns = [c for c in scores if c.startswith(f"{question}__")]
        if not columns:
            continue
        driver = scores[columns].mean(axis=1).round()
        for value in sorted(driver.dropna().unique()):
            pool = scores[driver == value]
            pick = pool.sample(n=min(per_value, len(pool)), random_state=seed)
            for _, call in pick.iterrows():
                rows.append({"question": question, "rounded_mean_score": value, "event_id": call["event_id"],
                             **{c.split("__", 1)[1]: call[c] for c in columns}})
    return pd.DataFrame(rows)


def summarize(folder):
    files, dist, agree = read(folder, "score_files"), read(folder, "distribution"), read(folder, "agreement")
    over, single, block = read(folder, "overlap"), read(folder, "one_at_a_time"), read(folder, "block")
    flow = read(folder, "sample_flow")
    if single is None:
        raise SystemExit(f"{folder}/one_at_a_time.csv is missing; run code/explore_llm_questions.py first.")
    leads = lead_rule.proposed_leads(single)
    models = [m for m in dict.fromkeys(single["model"]) if m != ex.CONSENSUS]
    meta = single.iloc[0]
    out = [f"# Screen summary: `{folder.name}`", "",
           f"**EXPLORATORY (not pre-specified), `specs_tried.md` Amendment 6.** Generated by "
           f"`code/summarize_llm_screen.py` from the CSVs in this folder (code `{meta.get('code_commit', '')}`, "
           f"run {meta.get('run_date', '')}). Outcome `{meta.get('outcome', '')}`, sample "
           f"`{meta.get('sample', '')}`, baseline `{meta.get('baseline', '')}`.", ""]

    out += ["## Scoring details (for the write-up)", ""]
    if files is not None:
        files = files.assign(file=files["file"].map(lambda f: Path(f).name))
        out.append(table(files, ["model", "file", "model_stamp", "prompt_version", "prompt_sha256", "rows",
                                 "valid_rows", "parse_errors", "run_from_utc", "run_to_utc"],
                         ["Model", "File", "Model as stamped", "Prompt", "Prompt SHA-256", "Rows", "Valid",
                          "Parse errors", "Run from (UTC)", "Run to (UTC)"]))
        failed = files[files["parse_errors"].fillna(0) > 0]
        for _, row in failed.iterrows():
            out.append(f"- `{row['file']}` parse failures: {row['parse_error_ids']}")
        out += ["", "Training cutoffs are not in the files; take them from Prof. Bowen's notes.", ""]
    if flow is not None:
        out += [f"Base sample: **{int(flow['n'].iloc[-1])} events**. Training day 0 through "
                f"{meta.get('holdout_train_through', '')}; holdout after.", ""]

    out += ["## Does each question vary? (for Gus)", ""]
    if dist is not None:
        d = dist[dist["model"] != ex.CONSENSUS].copy()
        d["null_share"] = d["n_null"] / d["n_valid_row"].replace(0, np.nan)
        low = d[d["low_variation"]].groupby("variable")["model"].apply(", ".join)
        nulls = d[d["null_share"] > MOSTLY_NULL_SHARE].groupby("variable")["model"].apply(", ".join)
        out.append(f"- Over 90% one answer: {len(low)} question(s)"
                   + ("".join(f"\n  - `{v}` ({m})" for v, m in low.items()) if len(low) else "."))
        out.append(f"- Over {MOSTLY_NULL_SHARE:.0%} null: {len(nulls)} question(s)"
                   + ("".join(f"\n  - `{v}` ({m})" for v, m in nulls.items()) if len(nulls) else "."))
        out += ["", "Full counts: `distribution.csv`.", ""]

    out += ["## Do the models agree?", ""]
    if agree is not None and not agree.empty:
        by_q = agree.groupby("variable")["weighted_kappa"].mean().sort_values()
        out.append(f"Median weighted kappa across question × model pairs: "
                   f"**{fmt(agree['weighted_kappa'].median(), 2)}** (range {fmt(agree['weighted_kappa'].min(), 2)} "
                   f"to {fmt(agree['weighted_kappa'].max(), 2)}). Least agreed: "
                   + ", ".join(f"`{v}` ({fmt(k, 2)})" for v, k in by_q.head(3).items()) + ".")
    else:
        out.append("Only one model, so agreement cannot be measured.")
    out.append("")

    out += ["## Do they re-measure what we already had?", ""]
    if over is not None:
        o = over[over["model"] != ex.CONSENSUS].sort_values("max_abs_rho_reference", ascending=False).head(5)
        out.append(table(o, ["model", "variable", "max_abs_rho_reference", "closest_reference"],
                         ["Model", "Question", "Largest abs. Spearman", "With"], {"max_abs_rho_reference": 2}))
        out.append("")

    out += ["## Each question added alone to Runs 1–2", ""]
    for model in models + ([ex.CONSENSUS] if ex.CONSENSUS in set(single["model"]) else []):
        rows = leads[leads["model"] == model].sort_values("p_value")
        k = rows["p_value"].notna().sum()
        out += [f"### {model}", "",
                f"{int((rows['p_value'] < 0.05).sum())} of {k} questions have p < 0.05; about "
                f"{0.05 * k:.1f} expected by chance.", "",
                table(rows, ["variable", "n", "coef", "p_value", "bh_q_within_model", "delta_mse",
                             "placebo_share", "passes_alone", "models_passing_same_sign", "proposed_lead"],
                      ["Question", "n", "pp per step", "p", "BH q", "Holdout ΔMSE", "Placebo", "Passes",
                       "Models passing, same sign", "Lead?"],
                      {"coef": 2, "p_value": 4, "delta_mse": 2}), ""]

    out += ["## Leads (Amendment 6 rule)", ""]
    found = leads[leads["proposed_lead"]]
    if len(models) < lead_rule.LEAD_MIN_MODELS:
        out.append(f"Only {len(models)} model, so no question can pass in {lead_rule.LEAD_MIN_MODELS} models: "
                   "no leads by construction.")
    elif found.empty:
        out.append("**None.** No question passes, with the same sign, in at least "
                   f"{lead_rule.LEAD_MIN_MODELS} models.")
    else:
        for variable, group in found.groupby("variable"):
            out.append(f"- `{variable}`: {', '.join(group['model'])}")
    out.append("")

    q20 = leads[leads["variable"] == "expected_investor_reaction"]
    if not q20.empty:
        best = leads[leads["variable"] != "expected_investor_reaction"].groupby("model")["delta_mse"].max()
        out += ["## Q20 benchmark (overall read of the call)", "",
                table(q20.assign(best_specific=q20["model"].map(best)),
                      ["model", "coef", "p_value", "delta_mse", "placebo_share", "best_specific"],
                      ["Model", "pp per step", "p", "Holdout ΔMSE", "Placebo", "Best specific question's ΔMSE"],
                      {"coef": 2, "p_value": 4, "delta_mse": 2, "best_specific": 2}), ""]

    if block is not None and not block.empty:
        out += ["## All questions as one block", "",
                table(block, ["model", "n_questions", "n", "delta_r2", "block_wald_p", "block_f_p_unclustered",
                              "delta_mse", "placebo_share"],
                      ["Model", "Questions", "n", "ΔR²", "Clustered Wald p", "Unclustered F p", "Holdout ΔMSE",
                       "Placebo"], {"block_wald_p": 4, "block_f_p_unclustered": 4, "delta_mse": 2}),
                "", "A blank clustered p means the block has more columns than the day-0 clusters allow "
                "(Amendment 6); the unclustered F p is too optimistic.", ""]

    sample = pd.DataFrame()
    if files is not None:
        base, _, _ = ex.base_sample(ex.nm.DEFAULT_COHORT, ex.nm.DEFAULT_DICTIONARY, ex.nm.DEFAULT_DAY0,
                                    primary_only=meta.get("sample", "primary") == "primary")
        raw_files = read(folder, "score_files")
        questions = top_questions(leads)
        sample = call_sample(raw_files, questions, set(base["event_id"]))
        sample.to_csv(folder / "call_check_sample.csv", index=False)
        out += ["## Calls to read (for Cammy)", "",
                f"`call_check_sample.csv`: {len(sample)} calls for {', '.join(f'`{q}`' for q in questions)} "
                f"(up to {CALLS_PER_VALUE} per score value, seed {ex.rm.SEED}), with each model's score. "
                "Read one locally with `python code/show_transcript.py <event_id>`; never paste transcript "
                "text anywhere.", ""]
    (folder / "SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    return folder / "SUMMARY.md", sample


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("screen", type=Path, help="Folder written by code/explore_llm_questions.py")
    args = parser.parse_args(argv)
    path, sample = summarize(args.screen)
    print(f"Wrote {path} and {len(sample)} rows of call_check_sample.csv (EXPLORATORY).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
